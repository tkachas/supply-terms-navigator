"""Сумма прописью → число. Нужна для сверки «цифрами» и «прописью» в договоре."""
from __future__ import annotations

import re

_UNITS = {
    "ноль": 0, "один": 1, "одна": 1, "одно": 1, "два": 2, "две": 2, "три": 3,
    "четыре": 4, "пять": 5, "шесть": 6, "семь": 7, "восемь": 8, "девять": 9,
    "десять": 10, "одиннадцать": 11, "двенадцать": 12, "тринадцать": 13,
    "четырнадцать": 14, "пятнадцать": 15, "шестнадцать": 16, "семнадцать": 17,
    "восемнадцать": 18, "девятнадцать": 19, "двадцать": 20, "тридцать": 30,
    "сорок": 40, "пятьдесят": 50, "шестьдесят": 60, "семьдесят": 70,
    "восемьдесят": 80, "девяносто": 90, "сто": 100, "двести": 200,
    "триста": 300, "четыреста": 400, "пятьсот": 500, "шестьсот": 600,
    "семьсот": 700, "восемьсот": 800, "девятьсот": 900,
}
_SCALES = {
    "тысяча": 10**3, "тысячи": 10**3, "тысяч": 10**3,
    "миллион": 10**6, "миллиона": 10**6, "миллионов": 10**6,
    "миллиард": 10**9, "миллиарда": 10**9, "миллиардов": 10**9,
}
_SKIP = {"рубль", "рубля", "рублей", "и"}


def words_to_int(text: str) -> int | None:
    """«один миллион двести тысяч» → 1200000. None, если текст не является числом прописью."""
    tokens = re.findall(r"[а-яё]+", text.lower().replace("ё", "е"))
    if not tokens:
        return None
    total = chunk = 0
    seen = False
    for tok in tokens:
        if tok in _UNITS:
            chunk += _UNITS[tok]
            seen = True
        elif tok in _SCALES:
            total += (chunk or 1) * _SCALES[tok]
            chunk = 0
            seen = True
        elif tok in _SKIP:
            continue
        else:
            return None  # посторонние слова, например «(в т.ч. НДС)» — не число
    return total + chunk if seen else None
